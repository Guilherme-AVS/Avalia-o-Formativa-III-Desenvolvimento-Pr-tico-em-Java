/**
 * Demonstra os três formatos de comentário apresentados na Aula 01.
 */
public class ComentariosJava {
    public static void main(String[] args) {
        // Comentário de uma linha.
        System.out.println("Comentário de uma linha acima.");

        /*
         * Comentário de múltiplas linhas.
         */
        System.out.println("Comentário de múltiplas linhas acima.");

        /**
         * Comentário de documentação (Javadoc).
         */
        System.out.println("O comentário de documentação pode ser usado para gerar documentação.");
    }
}
