public class FluxoCompilacao {
    public static void main(String[] args) {
        System.out.println("=== Fluxo de compilação e execução Java ===");
        System.out.println("1. MeuPrograma.java");
        System.out.println("   Código-fonte escrito pelo programador.");
        System.out.println("2. javac");
        System.out.println("   Compilador transforma o código-fonte em bytecode.");
        System.out.println("3. MeuPrograma.class");
        System.out.println("   Bytecode intermediário, independente de plataforma.");
        System.out.println("4. JVM");
        System.out.println("   Executa o bytecode no sistema operacional.");
        System.out.println("5. Computador");
        System.out.println("   Programa em execução.");

        System.out.println();
        System.out.println("Ideia central: .java -> javac -> .class -> JVM -> execução");
    }
}
