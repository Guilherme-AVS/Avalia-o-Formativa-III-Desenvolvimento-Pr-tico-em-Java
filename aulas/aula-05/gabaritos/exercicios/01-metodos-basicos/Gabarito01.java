public class Gabarito01 {
    public static void exibirMensagem() { System.out.println("Olá!"); }
    public static int dobrar(int n) { return n * 2; }
    public static int quadrado(int n) { return n * n; }
    public static void main(String[] args) {
        exibirMensagem();
        System.out.println(dobrar(5));
        System.out.println(quadrado(5));
    }
}
